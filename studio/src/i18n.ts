const TEXT: Record<Lang, Record<TextKey, string>> = { zh, en };

export function translate(
  lang: Lang,
  key: TextKey,
  values: Record<string, string | number> = {},
): string {
  return TEXT[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

/** A sentence with its values apart, so the page can show some of them, the names of roles and loops, as chips. */
export function sentenceParts(
  lang: Lang,
  key: TextKey,
  values: Record<string, string | number> = {},
): (string | { name: string; value: string })[] {
  const template = TEXT[lang][key];
  const parts: (string | { name: string; value: string })[] = [];
  let last = 0;
  for (const match of template.matchAll(/\{(\w+)\}/g)) {
    parts.push(template.slice(last, match.index));
    parts.push({ name: match[1]!, value: String(values[match[1]!] ?? "") });
    last = (match.index ?? 0) + match[0].length;
  }
  parts.push(template.slice(last));
  return parts;
}

export interface LangValue {
  lang: Lang;
  t: (key: TextKey, values?: Record<string, string | number>) => string;
}
export const LangContext = createContext<LangValue>({
  lang: "zh",
  t: (key, values) => translate("zh", key, values),
});
export const useLang = (): LangValue => useContext(LangContext);
